def list_integrations(*, category: str = "") -> list[dict[str, Any]]:
    if not category:
        return [dict(x) for x in INTEGRATION_CATALOG]
    return [dict(x) for x in INTEGRATION_CATALOG if x.get("category") == category]


def list_unity_templates() -> list[dict[str, Any]]:
    return [{"id": k, **v} for k, v in UNITY_TEMPLATES.items()]


def get_integration(integration_id: str) -> dict[str, Any] | None:
    for item in INTEGRATION_CATALOG:
        if item.get("id") == integration_id:
            return dict(item)
    return None


