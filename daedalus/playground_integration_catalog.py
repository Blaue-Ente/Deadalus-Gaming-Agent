def generate_integrations_doc(integration_ids: list[str]) -> str:
    lines = ["# Daedalus Integrations\n", "Репозитории и инструменти за този проект.\n"]
    for iid in integration_ids:
        item = get_integration(iid)
        if not item:
            continue
        lines.append(f"## {item['name']}\n")
        lines.append(f"- URL: {item['url']}\n")
        lines.append(f"- Роля: {item.get('daedalus_role', '')}\n")
        if item.get("warning"):
            lines.append(f"- ⚠️ {item['warning']}\n")
        if item.get("clone_into"):
            lines.append(f"- Clone path: `{item['clone_into']}`\n")
        lines.append(f"- Milestone: {item.get('studio_milestone', '—')}\n\n")
    return "\n".join(lines)
