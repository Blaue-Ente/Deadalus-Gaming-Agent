"""Unity bridge — export Daedalus studio artifacts for future Unity submenu integration.

Daedalus builds web/mobile prototypes + data schemas. Unity submenu will consume:
- studio/DATA_SCHEMA.md
- src/registry/entities.json, levels.json
- studio/unity/manifest.json (generated here)
- Optional C# stub files for ScriptableObject import
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any

UNITY_MANIFEST_PATH = "studio/unity/manifest.json"
UNITY_README_PATH = "studio/unity/README.md"
UNITY_STUBS_DIR = "studio/unity/Generated"


