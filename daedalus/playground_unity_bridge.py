def unity_bridge_readme() -> str:
    return """# Daedalus → Unity Bridge

This folder is produced by **Daedalus Studio** for a future Unity export workflow.

## What Daedalus already built
- `studio/PROJECT_RULES.md`, `ARCHITECTURE.md`, `DATA_SCHEMA.md`
- `src/registry/entities.json`, `levels.json`
- Gameplay prototype in Expo/Vite (reference implementation)

## Unity integration (planned submenu)
1. Open Daedalus Playground → Studio → **Export to Unity**
2. Clone or link a Unity template repo (URP mobile RPG)
3. Import `Generated/*.cs` stubs + JSON → ScriptableObject importers
4. Reuse balancing data from `entities.json` / DATA_SCHEMA

## Creative repo strategy
- Use open-source Unity creature-RPG templates as **shell**
- Daedalus owns **data + design docs + web vertical slice**
- Unity repo syncs registry JSON on each studio milestone merge

## Manual step today
Copy `manifest.json` + registry JSON into your Unity `Assets/DaedalusImport/`.
"""


def build_unity_manifest(
    *,
    project_name: str,
    preset: str,
    kind: str,
    plan: dict[str, Any] | None = None,
    trunk_files: dict[str, str] | None = None,
) -> dict[str, Any]:
    files = trunk_files or {}
    entities = files.get("src/registry/entities.json", "")
    levels = files.get("src/registry/levels.json", "")
    milestones = (plan or {}).get("milestones") or []
    return {
        "version": 1,
        "generator": "daedalus-studio",
        "exported_at": datetime.now(timezone.utc).isoformat(),
        "project_name": project_name,
        "source_kind": kind,
        "studio_preset": preset,
        "milestones_complete": [
            m.get("id") for m in milestones if isinstance(m, dict)
        ],
        "artifacts": {
            "data_schema": "studio/DATA_SCHEMA.md",
            "architecture": "studio/ARCHITECTURE.md",
            "entities_registry": (
                files.get("Assets/_Project/Data/Registry/entities.json")
                or files.get("src/registry/entities.json")
                or None
            ),
            "levels_registry": (
                files.get("Assets/_Project/Data/Registry/levels.json")
                or files.get("src/registry/levels.json")
                or None
            ),
        },
        "unity_recommended": {
            "engine": "Unity LTS",
            "render_pipeline": "URP",
            "template_repos_hint": [
                "Search: unity mobile rpg scriptableobject starter",
                "Search: unity creature collection template open source",
            ],
        },
        "import_steps": [
            "Create Unity project with URP",
            "Copy studio/unity/Generated/*.cs to Assets/Scripts/Daedalus/",
            "Import entities.json via custom ScriptableObject importer",
            "Wire combat logic from Daedalus ARCHITECTURE.md",
        ],
    }


def generate_unity_bridge_files(
    *,
    project_name: str,
    preset: str,
    kind: str,
    plan: dict[str, Any] | None = None,
    trunk_files: dict[str, str] | None = None,
) -> dict[str, str]:
    manifest = build_unity_manifest(
        project_name=project_name,
        preset=preset,
        kind=kind,
        plan=plan,
        trunk_files=trunk_files,
    )
    out: dict[str, str] = {
        UNITY_MANIFEST_PATH: json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        UNITY_README_PATH: unity_bridge_readme(),
        f"{UNITY_STUBS_DIR}/EntityData.cs": _csharp_entity_stub(),
    }
    # Embed registry snapshots for offline Unity import
    tf = trunk_files or {}
    if tf.get("src/registry/entities.json"):
        out["studio/unity/import/entities.json"] = tf["src/registry/entities.json"]
    if tf.get("src/registry/levels.json"):
        out["studio/unity/import/levels.json"] = tf["src/registry/levels.json"]
    return out


async def write_unity_bridge(slug: str, files: dict[str, str]) -> list[str]:
    from . import playground as pg

    written: list[str] = []
    for path, content in files.items():
        try:
            pg.write_file(slug, path, content)
            written.append(path)
        except Exception:
            pass
    return written
